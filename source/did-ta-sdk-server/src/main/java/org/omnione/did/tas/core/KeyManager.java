package org.omnione.did.tas.core;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.omnione.did.tas.exception.TaSdkErrorCode;
import org.omnione.did.tas.exception.TaSdkException;

import java.util.HashMap;
import java.util.Map;

/**
 * Key management component for TA SDK.
 *
 * <p>This class manages cryptographic key lifecycle (generation, signing)
 * for TA Server. It wraps FileWalletAdapter and provides protocol-specific
 * key naming conventions.</p>
 *
 * <p><b>Key Naming Conventions:</b></p>
 * <ul>
 *   <li>TAS keys: "assert", "auth", "keyagree", "invoke"</li>
 * </ul>
 *
 * <p><b>Note:</b> User and Entity keys are NOT managed by TA SDK.
 * They are managed by their respective wallets/apps.
 * ECDH ephemeral keys are automatically generated by BaseEcdhServiceImpl.</p>
 *
 * <p><b>Usage Example:</b></p>
 * <pre>
 * {@code
 * FileWalletAdapter walletAdapter = new FileWalletAdapter(walletConfig);
 * KeyManager keyManager = new KeyManager(walletAdapter);
 *
 * // Generate TAS assertion key
 * String keyId = keyManager.generateTasKey("assert");
 *
 * // Sign data
 * byte[] signature = keyManager.sign("assert", data);
 * }
 * </pre>
 */
@Slf4j
@RequiredArgsConstructor
public class KeyManager {

    private final FileWalletAdapter walletAdapter;

    // Cache for generated key IDs (in-memory only, not persistent)
    private final Map<String, String> keyIdCache = new HashMap<>();

    /**
     * Generate TAS key (assertion, authentication, keyagreement, invoke).
     *
     * @param purpose Key purpose ("assert", "auth", "keyagree", "invoke")
     * @return Generated key ID
     * @throws TaSdkException if key generation fails
     */
    public String generateTasKey(String purpose) {
        validatePurpose(purpose);

        try {
            log.info("Generating TAS key: {}", purpose);
            String generatedKeyId = walletAdapter.generateKey(purpose,
                org.omnione.did.common.datamodel.enums.crypto.EccCurveType.SECP256R1);
            keyIdCache.put(purpose, generatedKeyId);

            return generatedKeyId;
        } catch (org.omnione.did.common.exception.CommonSdkException e) {
            throw new TaSdkException(TaSdkErrorCode.SDK_KEY_GENERATION_FAILED, e);
        }
    }



    /**
     * Sign data with specified key.
     *
     * @param keyId Key identifier
     * @param data Data to sign
     * @return Signature bytes
     * @throws TaSdkException if signing fails
     */
    public byte[] sign(String keyId, byte[] data) {
        try {
            log.debug("Signing data with key: {}", keyId);
            return walletAdapter.sign(keyId, data);
        } catch (org.omnione.did.common.exception.CommonSdkException e) {
            throw new TaSdkException(TaSdkErrorCode.SDK_SIGNATURE_GENERATION_FAILED, e);
        }
    }

    /**
     * Sign string data with specified key.
     *
     * @param keyId Key identifier
     * @param data String data to sign
     * @return Signature bytes
     * @throws TaSdkException if signing fails
     */
    public byte[] sign(String keyId, String data) {
        return sign(keyId, data.getBytes(java.nio.charset.StandardCharsets.UTF_8));
    }

    /**
     * Validate key purpose.
     *
     * @param purpose Key purpose
     * @throws TaSdkException if purpose is invalid
     */
    private void validatePurpose(String purpose) {
        if (purpose == null || purpose.trim().isEmpty()) {
            throw new TaSdkException(TaSdkErrorCode.SDK_INVALID_PARAMETER,
                "Key purpose must not be null or empty");
        }
    }

    /**
     * Get wallet adapter (for advanced operations).
     *
     * @return FileWalletAdapter instance
     */
    public FileWalletAdapter getWalletAdapter() {
        return walletAdapter;
    }
}
